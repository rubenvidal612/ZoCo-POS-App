function svgPhoto(section, brand, name) {
  const ic = ICON[section] || ICON.general;
  const initials = (brand || name).replace(/[^A-Za-zÁÉÍÓÚÑ ]/g, '').split(/\s+/).slice(0, 2).map((w) => w[0] || '').join('').toUpperCase() || 'Z';
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 50 75">
    <rect width="50" height="75" fill="${ic.bg}"/>
    <g color="${ic.fg}">${ic.draw}</g>
    <rect x="0" y="58" width="50" height="17" fill="#0F172A" opacity=".85"/>
    <text x="25" y="68.5" text-anchor="middle" font-family="system-ui,sans-serif" font-size="5.2" font-weight="800" fill="#fff">${initials}</text>
  </svg>`;
  return 'data:image/svg+xml;charset=utf-8,' + encodeURIComponent(svg);
}

const build = (list, tag) => list.map(([name, brand, section], i) => ({
  name,
  section,
  brand,
  code: '',
  image: svgPhoto(section, brand, name),
}));

const head = (title) => `// Catálogo base de ${title} con marcas mexicanas.\n// Ilustraciones SVG propias (Open Food Facts no cubre este giro).\n`;

